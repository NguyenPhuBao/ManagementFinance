-- Bảng Role
CREATE TABLE Role (
    idrole INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rolename VARCHAR(50) NOT NULL UNIQUE,
    description VARCHAR(255)
);

